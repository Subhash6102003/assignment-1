import os
import io
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.pdfgen import canvas

EXPORTS_DIR = os.path.join(os.path.dirname(__file__), "exports")
os.makedirs(EXPORTS_DIR, exist_ok=True)

class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super(NumberedCanvas, self).__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748b"))
        
        # Header banner line
        self.setStrokeColor(colors.HexColor("#eceef2"))
        self.setLineWidth(0.5)
        self.line(40, letter[1] - 35, letter[0] - 40, letter[1] - 35)
        
        # Header text
        self.drawString(40, letter[1] - 30, "LaunchPulse GTM Studio — Autonomous Commercial Blueprint")
        self.drawRightString(letter[0] - 40, letter[1] - 30, "Confidential Strategy Dossier")

        # Footer line & text
        self.line(40, 45, letter[0] - 40, 45)
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawString(40, 32, "Generated by Claude via Model Context Protocol (MCP) | Zero AI Inside Web Codebase")
        self.drawRightString(letter[0] - 40, 32, page_text)
        self.restoreState()

def generate_gtm_report_pdf(product_data: dict, report_data: dict) -> str:
    """
    Generates a high-finish executive PDF for a GTM report dossier.
    Saves to the backend/exports directory and returns the absolute filepath.
    """
    safe_name = "".join(c if c.isalnum() else "_" for c in product_data.get("name", "Product"))
    filename = f"LaunchPulse_GTM_Dossier_{safe_name}_v1.pdf"
    filepath = os.path.join(EXPORTS_DIR, filename)

    doc = SimpleDocTemplate(
        filepath,
        pagesize=letter,
        leftMargin=40,
        rightMargin=40,
        topMargin=50,
        bottomMargin=55
    )

    styles = getSampleStyleSheet()
    
    # Custom styles
    brand_style = ParagraphStyle(
        'BrandTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=24,
        leading=28,
        textColor=colors.HexColor('#111827')
    )
    
    subtitle_style = ParagraphStyle(
        'Subtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=12,
        leading=16,
        textColor=colors.HexColor('#ff5c00')
    )

    h2_style = ParagraphStyle(
        'SectionH2',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=14,
        leading=18,
        textColor=colors.HexColor('#111827'),
        spaceBefore=14,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        'Body',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=15,
        textColor=colors.HexColor('#374151'),
        spaceAfter=8
    )

    story = []

    # Title & Header
    story.append(Spacer(1, 10))
    story.append(Paragraph(f"{product_data.get('name', 'Product')} — GTM Launch Dossier", brand_style))
    story.append(Spacer(1, 4))
    story.append(Paragraph(f"Category: {product_data.get('industry', 'Technology')} • Currency: {product_data.get('currency', 'USD')}", subtitle_style))
    story.append(Spacer(1, 12))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#ff5c00"), spaceAfter=14))

    # Unit Economics Metric Snapshot Table
    price = product_data.get('retail_price', 389.0)
    cost = product_data.get('unit_cost', 140.0)
    margin = product_data.get('projected_margin', 64.0)
    score = product_data.get('health_score', 82)

    table_data = [
        [
            Paragraph("<b>Target Retail Price</b>", body_style),
            Paragraph("<b>Unit Production Cost</b>", body_style),
            Paragraph("<b>Gross Margin</b>", body_style),
            Paragraph("<b>GTM Readiness Score</b>", body_style)
        ],
        [
            Paragraph(f"<font color='#ff5c00' size=14><b>${price:,.2f}</b></font>", body_style),
            Paragraph(f"<font color='#111827' size=14><b>${cost:,.2f}</b></font>", body_style),
            Paragraph(f"<font color='#12b76a' size=14><b>{margin}%</b></font>", body_style),
            Paragraph(f"<font color='#111827' size=14><b>{score}/100</b></font>", body_style)
        ]
    ]

    t = Table(table_data, colWidths=[130, 130, 130, 140])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#f8f9fb')),
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor('#eceef2')),
        ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#eceef2')),
        ('TOPPADDING', (0,0), (-1,-1), 8),
        ('BOTTOMPADDING', (0,0), (-1,-1), 8),
        ('LEFTPADDING', (0,0), (-1,-1), 10),
        ('RIGHTPADDING', (0,0), (-1,-1), 10),
    ]))
    story.append(t)
    story.append(Spacer(1, 14))

    # Value Proposition Callout
    hook_text = product_data.get('hook', 'Positioned for acute customer willingness to pay.')
    callout_data = [[
        Paragraph(f"<b>Core Value Proposition Hook:</b><br/><i>\"{hook_text}\"</i>", body_style)
    ]]
    callout_table = Table(callout_data, colWidths=[530])
    callout_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#fff5ee')),
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor('#ffd3bf')),
        ('LEFTPADDING', (0,0), (-1,-1), 14),
        ('RIGHTPADDING', (0,0), (-1,-1), 14),
        ('TOPPADDING', (0,0), (-1,-1), 10),
        ('BOTTOMPADDING', (0,0), (-1,-1), 10),
    ]))
    story.append(callout_table)
    story.append(Spacer(1, 14))

    # Narrative Sections
    sections = report_data.get("sections", [])
    for sec in sections:
        story.append(Paragraph(sec.get("title", "Strategic Section"), h2_style))
        content = sec.get("content", "").replace("\n", "<br/>")
        story.append(Paragraph(content, body_style))
        story.append(Spacer(1, 8))

    doc.build(story, canvasmaker=NumberedCanvas)
    return filepath
